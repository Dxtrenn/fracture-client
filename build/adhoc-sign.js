// electron-builder afterPack hook: give the Mac app a free ad-hoc signature.
// Apple Silicon refuses to open completely unsigned apps ("is damaged"); ad-hoc signed
// apps instead get the normal "unidentified developer" prompt that right-click → Open passes.
const { execFileSync } = require("child_process");
const path = require("path");

exports.default = async function adhocSign(context) {
  if (context.electronPlatformName !== "darwin") return;
  const app = path.join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`);
  console.log(`  • ad-hoc signing ${app}`);
  execFileSync("codesign", ["--force", "--deep", "--sign", "-", app], { stdio: "inherit" });
  execFileSync("codesign", ["--verify", "--deep", "--strict", app], { stdio: "inherit" });
};
