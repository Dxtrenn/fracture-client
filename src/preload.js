const { contextBridge, ipcRenderer, webUtils } = require("electron");

contextBridge.exposeInMainWorld("fractur", {
  window: (action) => ipcRenderer.invoke("window", action),
  getSettings: () => ipcRenderer.invoke("settings:get"),
  setSettings: (s) => ipcRenderer.invoke("settings:set", s),
  versions: () => ipcRenderer.invoke("versions"),
  getAccount: () => ipcRenderer.invoke("account:get"),
  login: () => ipcRenderer.invoke("account:login"),
  listAccounts: () => ipcRenderer.invoke("accounts:list"),
  selectAccount: (uuid) => ipcRenderer.invoke("accounts:select", uuid),
  removeAccount: (uuid) => ipcRenderer.invoke("accounts:remove", uuid),
  libraryList: (kind) => ipcRenderer.invoke("library:list", kind),
  libraryImport: (kind) => ipcRenderer.invoke("library:import", kind),
  libraryAddUrl: (kind, url, name) => ipcRenderer.invoke("library:addUrl", kind, url, name),
  libraryUpdate: (kind, id, changes) => ipcRenderer.invoke("library:update", kind, id, changes),
  libraryDelete: (kind, id) => ipcRenderer.invoke("library:delete", kind, id),
  libraryExport: (kind, id) => ipcRenderer.invoke("library:export", kind, id),
  applySkin: (id) => ipcRenderer.invoke("skin:apply", id),
  fixCrash: () => ipcRenderer.invoke("crash:fix"),
  deviceStart: () => ipcRenderer.invoke("account:deviceStart"),
  deviceCancel: () => ipcRenderer.invoke("account:deviceCancel"),
  openExternal: (url) => ipcRenderer.invoke("open-external", url),  launch: (opts) => ipcRenderer.invoke("launch", opts),
  openFolder: () => ipcRenderer.invoke("open-folder"),
  ping: (ip) => ipcRenderer.invoke("server:ping", ip),
  listMods: (v) => ipcRenderer.invoke("mods:list", v),
  toggleMod: (v, f) => ipcRenderer.invoke("mods:toggle", v, f),
  openMods: (v) => ipcRenderer.invoke("mods:open", v),
  deleteMod: (v, f) => ipcRenderer.invoke("mods:delete", v, f),
  searchModrinth: (q, v) => ipcRenderer.invoke("modrinth:search", q, v),
  installModrinth: (id, v) => ipcRenderer.invoke("modrinth:install", id, v),
  pathForFile: (file) => webUtils.getPathForFile(file),
  addFiles: (v, files) => ipcRenderer.invoke("mods:addFiles", v, files),
  scanImports: () => ipcRenderer.invoke("import:scan"),
  runImport: (dir, v, modsOnly) => ipcRenderer.invoke("import:run", dir, v, modsOnly),
  importFile: (v) => ipcRenderer.invoke("import:file", v),
  importFolder: (v) => ipcRenderer.invoke("import:folder", v),
  ownedCapes: () => ipcRenderer.invoke("capes:owned"),
  equipCape: (id) => ipcRenderer.invoke("capes:equip", id),
  on: (channel, cb) => ipcRenderer.on(channel, (_e, data) => cb(data)),
});
